"""Every arena map's name and loading screen, from the client's highest Map.dbc
and LoadingScreens.dbc, written as a Lua table for CENTURION_ArenaMaster."""
import os
import struct
import sys

sys.path.insert(0, r'C:\Projects\Gamedev\wow\clientedits\bountyboard')
import artlib  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))


def wdbc(name):
    data, src = artlib.extract('DBFilesClient\\' + name)
    assert data and data[:4] == b'WDBC', name
    n, fields, size, ssize = struct.unpack_from('<4I', data, 4)
    recs = data[20:20 + n * size]
    strings = data[20 + n * size:]

    def s(off):
        return strings[off:strings.index(b'\0', off)].decode('utf-8', 'replace')
    rows = [struct.unpack_from('<%dI' % fields, recs, i * size) for i in range(n)]
    return rows, s, src


if len(sys.argv) > 1:                    # a Map.dbc not yet in the client (just published)
    _data = open(sys.argv[1], 'rb').read()
    _orig = artlib.extract
    artlib.extract = lambda name: (_data, os.path.basename(sys.argv[1])) if name.endswith('Map.dbc') else _orig(name)
maps, ms, msrc = wdbc('Map.dbc')
screens, ss, ssrc = wdbc('LoadingScreens.dbc')
screen_file = {r[0]: ss(r[2]) for r in screens}
out = []
for r in maps:
    if r[2] != 4:                        # InstanceType 4 = arena
        continue
    name = ms(r[5])
    shot = screen_file.get(r[57], '')
    out.append((r[0], name, shot))
    print(r[0], name, r[57], shot)

lines = ['-- Generated by arena_screens.py from Map.dbc (%s) and LoadingScreens.dbc (%s).' % (msrc, ssrc),
         '-- Every arena map: its name and loading screen texture (no extension).',
         'CENTURION_ArenaMaster_Maps = {']
for mid, name, shot in sorted(out):
    tex = shot[:-4] if shot.lower().endswith('.blp') else shot
    lines.append('\t[%d] = { name = %s, screen = %s },' % (mid, '"%s"' % name.replace('"', '\\"'),
                                                          '"%s"' % tex.replace('\\', '\\\\')))
lines.append('}')
open(os.path.join(HERE, 'ArenaMaps.lua'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(out), 'arena maps')
